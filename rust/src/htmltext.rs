//! Port of smartinfo.py's remove_html_tags() plus the text extraction used by
//! the main loop and find_chapters_with_tokens():
//!   - drops div.MonTitle, div.ownerCompany, p.footer
//!   - drops the administrative sections (17-21 / Section7750-9051), keeping
//!     the drug-shortage subsections of section18 (section180, section181, ...)
//!   - full document text and per-section texts equivalent to
//!     BeautifulSoup's get_text(separator=" ")

use ego_tree::NodeId;
use scraper::node::Node;
use scraper::Html;
use std::collections::HashMap;
use std::sync::LazyLock;

// The Fachinfo HTML contains self-closed non-void elements like
// <div class="s14"/>. lxml (used by the Python version via BeautifulSoup)
// treats them as empty elements, while html5ever spec-correctly treats
// "<div/>" as an open tag — which would swallow following siblings into
// excluded sections. Expand them to <tag></tag> to match lxml.
static RE_SELF_CLOSED: LazyLock<regex::Regex> =
    LazyLock::new(|| regex::Regex::new(r"<(div|p)\b([^<>]*?)/>").unwrap());

const EXCLUDED_DIVS: [&str; 10] = [
    "section17",   // Zulassungsnummer
    "section18",   // Packungen
    "section19",   // Zulassungsinhaberin
    "section20",   // Stand der Information
    "section21",   // footer "Auto-generated by..." (used only by Java app)
    "Section7750", // Zulassungsnummer
    "Section7800", // Packungen
    "Section7850", // Zulassungsinhaberin
    "Section8000", // Stand der Information
    "Section9051", // footer "Auto-generated by..." (used only by C++ app)
];

pub struct DocText {
    pub full_text: String,
    /// (raw div id, section text) in document order
    pub sections: Vec<(String, String)>,
}

fn has_class(el: &scraper::node::Element, class: &str) -> bool {
    el.attr("class")
        .map(|c| c.split_whitespace().any(|t| t == class))
        .unwrap_or(false)
}

fn subtree_text(node: ego_tree::NodeRef<Node>) -> String {
    let mut parts: Vec<&str> = Vec::new();
    for d in node.descendants() {
        if let Node::Text(t) = d.value() {
            parts.push(&t.text);
        }
    }
    parts.join(" ")
}

pub fn extract(html_str: &str) -> DocText {
    let html_str = RE_SELF_CLOSED.replace_all(html_str, "<${1}${2}></${1}>");
    let mut doc = Html::parse_document(&html_str);

    let mut mon_title: Option<NodeId> = None;
    let mut owner_company: Option<NodeId> = None;
    let mut footer: Option<NodeId> = None;
    let mut first_div_by_id: HashMap<String, NodeId> = HashMap::new();
    let mut drugshortage: Vec<NodeId> = Vec::new();

    for node in doc.tree.root().descendants() {
        if let Node::Element(el) = node.value() {
            match el.name() {
                "div" => {
                    if mon_title.is_none() && has_class(el, "MonTitle") {
                        mon_title = Some(node.id());
                    }
                    if owner_company.is_none() && has_class(el, "ownerCompany") {
                        owner_company = Some(node.id());
                    }
                    if let Some(id) = el.attr("id") {
                        let idl = id.to_lowercase();
                        if idl.starts_with("section18") && idl != "section18" {
                            drugshortage.push(node.id());
                        }
                        first_div_by_id
                            .entry(id.to_string())
                            .or_insert_with(|| node.id());
                    }
                }
                "p" => {
                    if footer.is_none() && has_class(el, "footer") {
                        footer = Some(node.id());
                    }
                }
                _ => {}
            }
        }
    }

    if let Some(id) = mon_title {
        doc.tree.get_mut(id).unwrap().detach();
    }
    if let Some(id) = owner_company {
        doc.tree.get_mut(id).unwrap().detach();
    }

    for d in EXCLUDED_DIVS {
        if let Some(&nid) = first_div_by_id.get(d) {
            if d == "section18" {
                // keep drugshortage subsections: move them in front of section18
                // (Python inserts copies before decomposing section18)
                for &ds in &drugshortage {
                    doc.tree.get_mut(nid).unwrap().insert_id_before(ds);
                }
            }
            doc.tree.get_mut(nid).unwrap().detach();
        }
    }

    if let Some(id) = footer {
        doc.tree.get_mut(id).unwrap().detach();
    }

    // <br/> is replaced by " " in Python; with a " " separator between text
    // nodes this has no effect on the extracted token stream, so it is skipped.

    let root = doc.tree.root();
    let full_text = subtree_text(root);

    let mut sections: Vec<(String, String)> = Vec::new();
    for node in root.descendants() {
        if let Node::Element(el) = node.value() {
            if el.name() == "div" {
                if let Some(id) = el.attr("id") {
                    if id.starts_with("section") || id.starts_with("Section") {
                        sections.push((id.to_string(), subtree_text(node)));
                    }
                }
            }
        }
    }

    DocText {
        full_text,
        sections,
    }
}
